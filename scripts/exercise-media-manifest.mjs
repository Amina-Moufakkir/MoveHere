L.push('descends, how far a limb travels toward the floor, where the feet sit. Fixing such a value');
L.push('parameterises a stated fact and is permitted, provided the value chosen is not itself an');
L.push('excluded named landmark. A detail the instruction states nothing about, and which selects');
