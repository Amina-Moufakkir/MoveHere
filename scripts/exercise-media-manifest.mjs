/**
 * The asset production manifest.
 *
 * Enumerates every exercise in the validated matrix and every *presentation
 * pairing* it can legitimately be shown in — that is, every distinct thing a
 * user can actually be looking at on the workout screen, which is a movement
 * *plus* the structure the generator cited for it.
 *
 * A movement is not one picture. `step-up` performed from a bench and
 * `step-up` performed from stairs are the same entry in the catalog and two
 * different things to draw, and the screen knows which one it asked for. So
 * the unit of art is the pairing, not the exercise.
 *
 * Derived, never transcribed. The set printed here is exactly the set
 * `check:exercise-media` accepts: anything commissioned from this manifest
 * passes the gate by construction, and anything the matrix stops claiming
 * disappears from the next run rather than lingering as a stale brief.
 */

import { loadMatrix } from '../src/domain/matrix-loader.ts';
import { AUTHORED_MATRIX } from '../src/domain/exercise-catalog.ts';
import { FEATURE_REGISTRY } from '../src/domain/feature-registry.ts';
import { readFileSync } from 'node:fs';

const loaded = loadMatrix(AUTHORED_MATRIX);
if (!loaded.ok) {
  console.error('the shipped matrix does not load; there is nothing to commission');
  process.exit(1);
}
const matrix = loaded.matrix;

const featureLabel = Object.fromEntries(
  FEATURE_REGISTRY.supported.map((f) => [String(f.id), f.label]),
);

/** What already exists, read from the registry so the manifest shows real progress. */
const registry = readFileSync('mobile/media/exercise-visuals.ts', 'utf8');
const existing = new Set(
  [...registry.matchAll(/exerciseId:\s*'([^']+)'[\s\S]*?featureId:\s*(?:'([^']+)'|(null))/g)].map(
    (m) => `${m[1]}@${m[2] ?? '-'}`,
  ),
);

const pairingsFor = (exerciseId) => {
  const out = [];
  for (const d of matrix.environmentIndependent) {
    if (String(d.exerciseId) === exerciseId) {
      out.push({ featureId: null, label: 'No equipment', variation: null, id: String(d.id) });
    }
  }
  for (const c of matrix.compatibilities) {
    if (String(c.exerciseId) !== exerciseId) continue;
    out.push({
      featureId: String(c.featureId),
      label: featureLabel[String(c.featureId)] ?? String(c.featureId),
      variation: c.variationLabel ?? null,
      id: String(c.id),
    });
  }
  return out;
};

const rows = matrix.exercises.map((e) => ({ e, pairings: pairingsFor(String(e.id)) }));
const total = rows.reduce((n, r) => n + r.pairings.length, 0);
const done = rows.reduce(
  (n, r) => n + r.pairings.filter((p) => existing.has(`${String(r.e.id)}@${p.featureId ?? '-'}`)).length,
  0,
);

const L = [];
L.push('# Exercise media manifest');
L.push('');
L.push('<!-- Generated by `npm run media:manifest`. Do not edit by hand. -->');
L.push('');
L.push(
  `Matrix \`${String(matrix.version)}\` — **${rows.length} exercises**, ` +
    `**${total} presentation pairings**, ${done} illustrated, ${total - done} outstanding.`,
);
L.push('');
L.push(
  'A *presentation pairing* is one movement as the workout screen can actually show it: the ' +
    'exercise plus the structure the generator cited for it. The same movement on a bench and ' +
    'on stairs are two pairings and two assets.',
);
L.push('');
L.push(
  'The visuals are project-created and have not been reviewed by a qualified fitness ' +
    'professional. Nothing commissioned from this list may depict, or be captioned with, a ' +
    'claim that a structure is safe, sound, or inspected — the app states what it can and ' +
    'cannot assess in its own copy, and a picture must not quietly say otherwise.',
);
L.push('');
L.push('**A visual may only illustrate a claim the matrix already holds.** Every key below is one');
L.push('the matrix holds; commissioning anything not on this list will fail `check:exercise-media`.');
L.push('');
L.push('## Production brief');
L.push('');
L.push(
  'Derived from the approved Bench Step-up specimen (`step-up@park-bench`), which is the style ' +
    'reference for everything else on this list.',
);
L.push('');
L.push('- **3:2 landscape.** The slot sizes itself from the asset, so one ratio across the set is');
L.push('  what keeps the movement frame the same size on every screen of a session.');
L.push('- **One cast, one style.** The same model, clothing, and rendering style throughout. A');
L.push('  session shows several of these in a row, and a change of cast reads as a change of');
L.push('  subject.');
L.push('- **Daylight master first.** The dark counterpart is *derived from the approved daylight');
L.push('  composition*, never independently reimagined: same pose, same framing, same structure,');
L.push('  palette only. Two independently drawn versions of one movement are two depictions, and');
L.push('  a theme switch mid-session would silently swap which one the user is being shown.');
L.push('- **Dynamic movements: two phases, left to right.** Start on the left, finish on the');
L.push('  right, in that reading order.');
L.push('- **Static holds: a single centred pose.** A held position has no second phase, and');
L.push('  inventing one would depict movement the prescription does not ask for.');
L.push('- **The cited structure or surface, and nothing else.** Environment-independent visuals');
L.push('  contain no equipment and no invented environmental structure of any kind.');
L.push('- **Nothing written inside the frame.** No exercise title, cues, prescriptions,');
L.push('  muscles-worked claims, provenance, or safety claims. All of that already exists in the');
L.push('  app, where it is versioned, reviewed as content, and rendered at a size a person can');
L.push('  read.');
L.push('');
L.push('**Every depiction encodes judgement.** Framing, joint angles, how far a phase travels,');
L.push('and where the movement is cut into phases are all choices, and a simple movement does not');
L.push('make them neutral. A low-complexity asset is cheaper to produce and a smaller thing to get');
L.push('wrong; it is not a checked one. Nothing on this list, at any complexity, is more than a');
L.push('project-created demonstration pending professional review.');
L.push('');
L.push('**Mapping identity is not composition identity.** Every key below stays distinct: its own');
L.push('asset file, its own registry entry, its own lookup. Where the movement itself is identical');
L.push('across contexts, the approved human pose and composition may be reused between those');
L.push('assets, changing only the accurately cited environment. Reuse the person, never the claim');
L.push('\u2014 what makes two pairings two assets is the structure the screen cited for each, so');
L.push('that is exactly the part that must be redrawn.');
L.push('');
L.push('## Pairings');
L.push('');

for (const { e, pairings } of rows) {
  const kinds = e.prescriptionKinds.join(', ');
  L.push(`### ${e.name}`);
  L.push('');
  L.push(
    `\`${String(e.id)}\` · ${e.pattern} · ${e.laterality} · dosed by ${kinds} · ` +
      `${pairings.length} pairing${pairings.length === 1 ? '' : 's'}`,
  );
  L.push('');
  L.push('Cues the app owns (the visual demonstrates the movement; it does not instruct):');
  for (const cue of e.cues) L.push(`- ${cue}`);
  L.push('');
  L.push('| Asset key | Performed with | Variation | Matrix entry | Status |');
  L.push('| --- | --- | --- | --- | --- |');
  for (const p of pairings) {
    const key = `${String(e.id)}@${p.featureId ?? '-'}`;
    L.push(
      `| \`${key}\` | ${p.label} | ${p.variation ?? '—'} | \`${p.id}\` | ` +
        `${existing.has(key) ? 'illustrated' : 'outstanding'} |`,
    );
  }
  L.push('');
}

L.push('## Every key, flat');
L.push('');
L.push('```');
for (const { e, pairings } of rows) {
  for (const p of pairings) L.push(`${String(e.id)}@${p.featureId ?? '-'}`);
}
L.push('```');
L.push('');

console.log(L.join('\n'));
